def _nl(raw):
    return '\r\n' if '\r\n' in raw else '\n'


def files():
    seen = []
    for _, f, _, _ in MUTS:
        if f not in seen:
            seen.append(f)
    return seen


def apply(k):
    name, path, old, new = MUTS[k]
    raw = io.open(path, encoding='utf-8', newline='').read()
    nl = _nl(raw)
    o = old.replace('\n', nl)
    n = new.replace('\n', nl)
    if raw.count(o) != 1:
        sys.stderr.write('%s: ANCHOR NOT UNIQUE (%d) in %s\n' % (name, raw.count(o), path))
        return False
    if o == n:
        sys.stderr.write('%s: MUTANT IDENTICAL TO BASE\n' % name)
        return False
    io.open(path, 'w', encoding='utf-8', newline='').write(raw.replace(o, n, 1))
    os.utime(path, None)   # NOW, never the future -- see the sweep's header
    return True


def main():
    if len(sys.argv) >= 2 and sys.argv[1] == '--count':
        print(len(MUTS))
        return 0
    if len(sys.argv) >= 2 and sys.argv[1] == '--files':
        for f in files():
            print(f)
        return 0
    if len(sys.argv) >= 3 and sys.argv[1] == '--name':
        print(MUTS[int(sys.argv[2])][0])
        return 0
    if len(sys.argv) >= 3 and sys.argv[1] == '--file':
        print(MUTS[int(sys.argv[2])][1])
        return 0
    if len(sys.argv) >= 3 and sys.argv[1] == '--equiv':
        proof = EQUIVALENT.get(sys.argv[2])
        if proof is None:
            return 1
        print(proof)
        return 0
    if len(sys.argv) >= 3 and sys.argv[1] == '--apply':
        return 0 if apply(int(sys.argv[2])) else 9
    sys.stderr.write('usage: --count | --files | --name K | --file K | --apply K\n')
    return 2


if __name__ == '__main__':
    sys.exit(main())
