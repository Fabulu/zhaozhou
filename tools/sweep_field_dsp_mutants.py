"""Mutants for tools/sweep_field_dsp.sh — the Field IR shared arithmetic engine.

Held in Python rather than in the shell for the reason
sweep_terrain_lod_mutants.py already gives: multi-line anchors inside a bash
array are a quoting hazard, and this sweep spans SEVEN files rather than one.

EACH ENTRY IS (name, file, old, new). The anchors are exact and must be UNIQUE
in their file; the preflight refuses to start otherwise, which is what stops a
mutation from silently landing in the wrong place.

WHAT IS BEING SWEPT, and why these and not the old list. The 2026-08-23
rearchitecture replaced ten parallel op units, each with its own multiplier,
with ONE shared lane, ONE integer root, ONE sine table and ONE reciprocal.
Almost none of the engine's previous mutants reach that logic, because it did
not exist. The families here are the new ones:

  * the LANE itself -- operand holding, product width, valid timing;
  * the READ-WALK ACCUMULATOR -- and specifically LOAD-versus-ACCUMULATE, which
    is the defect a shared accumulator can have and a parallel design cannot.
    It is invisible to every test that runs one op at a time, so it is the
    reason section 13 of field_seq_directed exists, and the reason it must be
    proven to FAIL on a mutant rather than merely pass on the shipped code;
  * the MUXES -- the root's, the sine table's, the reciprocal's and the lane's.
    Each selects on the executing opcode because only one instruction is ever
    live; a mux that leaks another unit's request is the shape of defect this
    architecture newly admits;
  * the SCHEDULE -- Q_LATCH reading from `ins_*_i`, Q_GATH existing at all, the
    slot indices. These are what keep MUL/MAD/DOT2/DOT3 at six clocks, and
    every one of them is a silent latency regression if it breaks;
  * the PER-OP WALKS that were rewritten around the lane's two-cycle latency --
    RCP's split correction product, NORMALIZE's four-step correction chain,
    RING's two reciprocal calls, CURVE's Horner chain, NOISE's and ROT's issue
    lists.
"""

