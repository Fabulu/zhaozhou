        "SOURCES ${ZHAO_PACKET_E_MUX_SOURCES}",
        "hold_guard_valid pe_m1 EXPECT_RENDER_ASSET_HOLD_GUARD_VALID_MUTANT",
        "drift_subowner pe_m2 EXPECT_RENDER_ASSET_DRIFT_SUBOWNER_MUTANT",
