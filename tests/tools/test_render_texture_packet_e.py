        "relabel_refusal PACKET_E_EXPECT_RELABEL_REFUSAL_ERR",
        "refusal_native_arith PACKET_E_EXPECT_REFUSAL_NATIVE_ARITH",
        "drop_held_refusal PACKET_E_EXPECT_DROP_HELD_REFUSAL",
