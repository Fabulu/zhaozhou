// zhao_mem_guard.sv — region/ownership checker between EVERY fabric VRAM
// client and the memory system (plan W2.5). Law: spec/memory_rules.md §5;
// contract design/contracts/MEM.GUARD.md.
//
// Phase-2 region map (mode-independent — both slots are sized for the
// LARGEST canvas, so a mode switch never moves a slot):
//   FB slot 0 : [0x0000_0000, 0x0003_C000)   245,760 B  (DRAM bank 0)
//   FB slot 1 : [0x0200_0000, 0x0203_C000)   245,760 B  (DRAM bank 1 —
//               the W2.7 bank split; see zhao_pkg ZHAO_FB_SLOT1_BASE)
//   everything else: unmapped — violation by construction.
//   ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
//
// Phase-3 extensions, each a window opened WITH the block that needed it:
//   RENDER.ASSET_POOL : [0x06A0_0000, 0x0800_0000)  22 MiB, ENGINE1, READ-only
//   POST.ECHO capture : [0x05C0_0000, 0x05C3_C000)  245,760 B, ENGINE0,
//                       WRITE-only, lease-gated (ruling R7, section 5g)
//   (and ENGINE0 may READ its leased FB window: the POST.COMPOSITE lease)
//   TERRAIN.PAGE_POOL : [0x0400_0000, 0x054E_0000)  20.875 MiB,
//                       TERRAIN.BUILD, WRITE (pages in) and READ (F sheets
//                       out) -- ONE window, TWO arms, TWO theorems
//                       (rulings T2 / T3 / T4, §5b)
//   TERRAIN.DEVSTORE  : [0x0586_0000, 0x058B_0000)  320 KiB,
//                       TERRAIN.BUILD, WRITE (the page's deviation records
//                       and the patch's history row) and READ (the LOD
//                       pass's per-frame fetch) -- ONE window, TWO arms,
//                       TWO theorems (ruling R242, §5b)
//   GEOM.PARAMBUF     : [0x0600_0000, 0x0640_0000) view 0, 4 MiB
//                       [0x0640_0000, 0x0680_0000) view 1, 4 MiB
//                       [0x0680_0000, 0x06A0_0000) shared scratch, 2 MiB
//                       ENGINE1, READ (either view), WRITE (the LEASED view
//                       only) and BOTH directions in the ACQUIRED scratch --
//                       THREE regions, THREE arms, and a request must lie
//                       wholly inside ONE of them (owner completion ruling
//                       ITEM 4, §5c). RENDER.ASSET_POOL above stays
//                       READ-ONLY to ENGINE1 and this ruling does not widen
//                       it: a1_pb_asset_still_ro.
//
// Ownership law:
//   * SCANOUT owns BOTH slots, READ-ONLY (a write is a violation).
//   * BLIT_DMA owns exactly the CMD-granted slot window
//     [slot_base, slot_base + blit_span) — blit_span = canvas_bytes(mode),
//     written by CMD.SCHEDULER at frame grant. Writes only (Phase-2 blit
//     never reads VRAM: a read is a violation by construction).
//     map_valid=0 (no grant this frame) => deny-all.
//     ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
//   * ENGINE0/ENGINE1/DEBUG own nothing in Phase 2 (reserved ports) —
//     violation by construction. (ENGINE0 and ENGINE1 acquired windows in
//     Phase 3; DEBUG still owns nothing, and neither does the unspent
//     client 5.)
//     ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
//   * TERRAIN.BUILD owns TERRAIN.PAGE_POOL IN BOTH DIRECTIONS, and no other
//     client reaches it in either. Spatially the WHOLE pool, not the LOADING
//     slot T2 eventually wants — the difference is spelled out at
//     `terrain_ok` below rather than left for a reader to discover.
//     ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
//
// Request law: len 1..64 bytes; byte_enable must be the FULL contiguous mask
// over [addr, addr+len) (Phase-2 clients issue whole spans; partial-word
// tails are a Phase-3 map concern). Span arithmetic is done at 32 bits so
// addr+len can never wrap past the map.
//
// Verdict: fixed 1 cycle (registered rsp). A passing request is forwarded to
// the arbiter port and held there until the arbiter grants it (ready/valid
// end-to-end — the guard never drops a legal request, never invents one).
// A denied request is ANSWERED (guard_violation pulse + count + latched
// trace record, charter §29-17 lane) and NOTHING is forwarded — the formal
// property mem_guard_no_escape proves no violating request ever reaches the
// arbiter port and no partial forward exists.
//
// Conservative SystemVerilog subset only (charter §2). Lint: clean under
// `verilator --lint-only -Wall` (lint_mem_guard CTest).

module zhao_mem_guard_pbview_mutant
  import zhao_pkg::*;
(
  input  logic clk,
  input  logic rst_n,

  // client port (muxed upstream; the client field identifies the owner)
  input  zhao_guard_req_t req,
  output zhao_guard_rsp_t rsp,

  // region map inputs (CMD.SCHEDULER grants at frame start; deny-all below)
  input  logic        map_valid,     // a blit grant exists this frame
  input  logic        blit_slot,     // 0/1: the leased FB slot
  input  logic [31:0] blit_span,     // granted bytes (canvas_bytes(mode))
  // WHICH WRITER HOLDS THE LEASE. 0 = DEBUG.FRAMEBLIT, 1 = RASTER.FBWRITE.
  // Two blocks now write an inactive framebuffer slot and they share the
  // SPATIAL window but not the TEMPORAL permission: a second overlapping region
  // entry would copy the same address law, cost more plumbing, and still not
  // stop them corrupting each other. VIDEO.SLOTMGR already guarantees one lease
  // at a time with a generation, so the lease is where the writer is named.
  //
  // A v1 frame uses the renderer or DebugFrameBlit, never both.
  //
  // ENFORCED-BY: tests/formal/formal_mem_guard.sv:a1_region
  input  logic        fb_writer,

  // THE PUBLISHED-RESOURCE REGION (owner ruling R32, 2026-09-19). MEM.UPLOAD --
  // TERRAIN_BUILD's client -- may WRITE here, and only here, inside
  // RENDER.ASSET_POOL: the host-configured destination region whose uploads
  // MEM.UPLOAD publishes into the residency directory (spec/memory_rules.md
  // 5f.1). A region that does not lie wholly inside the asset pool OPENS
  // NOTHING -- it is refused, not clamped. Tie `res_valid` low on a guard
  // instance whose client is never TERRAIN_BUILD.
  // ENFORCED-BY: tests/formal/formal_mem_guard.sv:a1_resource_*
  input  logic        res_valid,
  input  logic [31:0] res_base,
  input  logic [31:0] res_span,

  // GEOM.PARAMBUF'S FRAME LEASE (owner completion ruling ITEM 4, 2026-09-22;
  // spec/memory_rules.md 5c). THREE ports, and each one is a REFUSAL rather
  // than a convenience -- with all three low, ENGINE1's permissions are
  // byte-for-byte what they were before this ruling, which is the property
  // that makes "no blanket bank-3 permission" checkable rather than claimed.
  //
  //   pb_lease_valid   ENGINE1 holds the arena this frame at all. Deny-all
  //                    below, exactly like `map_valid`: a guard instance
  //                    whose client is never ENGINE1 ties it low and the
  //                    whole of 5c stays closed.
  //   pb_wr_view       0/1 -- WHICH view ENGINE1 may WRITE. The two views are
  //                    disjoint "for the same reason the two FB slots are"
  //                    (5c): one is being BUILT while the other is being
  //                    READ, so a write arm that did not name a view would
  //                    let the producer overwrite the frame the renderer is
  //                    walking. This is `fb_writer`'s shape, for `fb_writer`'s
  //                    reason.
  //   pb_scratch_valid the shared prefetch/chunk scratch is ACQUIRED. Item 4:
  //                    "Shared scratch has explicit ownership and release
  //                    rather than being unowned temporary memory." Release
  //                    is deasserting it, and while it is low the scratch is
  //                    unmapped for everybody.
  //
  // THE RESIDUAL THIS CREATES IS STATED HERE RATHER THAN LEFT TO BE FOUND,
  // because it is the defect class this repository lost a week to. Item 4
  // says "Carry request identity WITH the request; do not validate a queued
  // request against a later global view selector." `pb_wr_view` IS a global
  // selector, and this block is combinational over the request it is being
  // OFFERED -- so a request queued under view 0 and still unaccepted when the
  // lease flips to view 1 would be judged by the NEW selector. MEM.GUARD
  // cannot close that on its own: `zhao_guard_req_t` has no view field and
  // widening it would change every client's ABI.
  //
  // It is closed at the PRODUCER, where the identity actually lives.
  // `zhao_geom_paramarena` latches the view at frame seal, derives every
  // address from the LATCHED base, and refuses to flip the lease while
  // `wr_outstanding_o != 0` -- so no request ever outlives the selector that
  // admitted it. That drain precondition is the protection, it is counted by
  // `view_flip_blocked_o`, and `tests/mutants/zhao_geom_paramarena_drain_mutant.sv`
  // is the committed fault that removes it and makes the directed test FAIL.
  // ENFORCED-BY: tests/formal/formal_mem_guard.sv:a1_pb_*
  input  logic        pb_lease_valid,
  input  logic        pb_wr_view,
  input  logic        pb_scratch_valid,

  // forwarded side (guard -> MEM.VRAM.ARBITER), ready/valid
  output zhao_arb_req_t arb_req,
  input  zhao_arb_rsp_t arb_rsp,

  // events / trace (violations are not a catalog counter; they trace to the
  // harness with the full request — the saved-failing-vector lane)
  output logic           guard_violation,      // one-cycle pulse
  output logic [31:0]    guard_violations,
  output zhao_guard_req_t guard_violation_req   // latched violating request
);

  // ------------------------------------------------------------ verdict ----
  // full contiguous byte mask over len bytes
  function automatic logic [63:0] mask_of(input logic [6:0] len_b);
    mask_of = '0;
    for (int b = 0; b < 64; b++) begin
      if (b < len_b) mask_of[b] = 1'b1;
    end
  endfunction

  logic [31:0] addr32, end32;
  logic        len_ok, be_ok, shape_ok;
  logic        scan_ok, blit_ok, render_asset_ok;
  logic        pass_ok;

  assign addr32   = {5'b0, req.addr};
  assign end32    = addr32 + {25'b0, req.len};   // 32-bit: cannot wrap the map
  assign len_ok   = (req.len >= 7'd1) && (req.len <= 7'd64);
  assign be_ok    = (req.be == mask_of(req.len));
  assign shape_ok = len_ok && be_ok;

  // scanout: read-only, within EITHER FB slot. The slots are DISJOINT
  // regions since the bank split (zhao_pkg ZHAO_FB_SLOT1_BASE note): the
  // old single-comparison form (end <= SLOT1+SPAN) relied on the slots
  // being contiguous and would have admitted reads from the hole between
  // them. A <=64-B request can never bridge from slot 0 into slot 1, so
  // per-slot containment is exact.
  assign scan_ok = !req.write
                 && ((end32 <= ZHAO_FB_SLOT0_BASE + ZHAO_FB_SLOT_SPAN)
                     || ((addr32 >= ZHAO_FB_SLOT1_BASE)
                         && (end32 <= ZHAO_FB_SLOT1_BASE + ZHAO_FB_SLOT_SPAN)));

  // blit: write-only, within the granted slot window.
  // blit_span is clamped to the slot's own span before use. CMD.SCHEDULER is
  // specified to write canvas_bytes(mode) (<= ZHAO_FB_SLOT_SPAN), but the
  // guard must not TRUST that: an over-large span made blit_base + blit_span
  // wrap 32 bits, and a wrapped window admitted writes far outside the map —
  // an escape, in the one block whose entire contract is that no escape
  // exists. Clamping keeps every legal request legal (they never exceed the
  // slot) and closes the wrap by construction. Removing the clamp fails
  // the proof again (design/formal_runs.yml notes).
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
  logic [31:0] blit_base, blit_end, blit_span_eff;
  assign blit_base     = blit_slot ? ZHAO_FB_SLOT1_BASE : ZHAO_FB_SLOT0_BASE;
  assign blit_span_eff = (blit_span > ZHAO_FB_SLOT_SPAN) ? ZHAO_FB_SLOT_SPAN : blit_span;
  assign blit_end      = blit_base + blit_span_eff;
  // The window check, shared by both writers. `fb_window_ok` is the name the
  // ruling gives it; `blit_ok` is kept as the identifier so the proof's own
  // wording still lines up with the code it proves.
  assign blit_ok       = req.write && map_valid
                         && (addr32 >= blit_base) && (end32 <= blit_end);

  // render asset pool: READ-ONLY, ENGINE1's shared geometry/texture region
  // (spec/memory_rules.md 5f). Historical geometry constants remain aliases.
  // The original reason for the window remains: every MESHFETCH descriptor read
  // otherwise landed on `default: pass_ok = 1'b0`; Packet E now serializes
  // immutable texture-line reads through the same local ENGINE1 owner.
  //
  // A THIRD WINDOW IS OPENED HERE, unlike the ENGINE0 change which admitted a
  // client to an existing one -- so it is stated plainly rather than folded in.
  // What keeps the no-escape guarantee intact is that the window is
  // READ-ONLY and its bounds are CONSTANTS: `!req.write` means nothing in this
  // region can alter a frame buffer, and BASE + SPAN is 0x0800_0000 exactly,
  // computed at elaboration, so the wrap the blit clamp exists to prevent
  // cannot arise here. No map input is consulted, so unlike the blit window
  // this one is not frame-scoped and does not depend on `map_valid`.
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
  assign render_asset_ok = !req.write
                  && (addr32 >= ZHAO_RENDER_ASSET_BASE)
                  && (end32  <= ZHAO_RENDER_ASSET_BASE + ZHAO_RENDER_ASSET_SPAN);

  // terrain page pool: TERRAIN.BUILD's bank-2 region, WRITE for the loader and
  // READ for the writeback (rulings T2 / T3 / T4, spec/memory_rules.md 5b).
  // This is the FOURTH window, and like the asset pool it is stated plainly
  // rather than folded into an existing one.
  //
  // IT IS THE NARROWEST READING OF T2/T4 THAT LETS A PAGE BE LOADED AND ITS
  // DIRTY SHEET BE SAVED AT ALL:
  //   * ONE region of the six T2 names in bank 2. RESIDENT_MIP_POOL,
  //     COMPOSED_HEIGHT, COMPOSED_VELOCITY, WRITEBACK_STAGING and
  //     COMPOSED_MIP_POOL stay unmapped until the blocks that touch them
  //     exist.
  //
  //     RE-EXAMINED AND DELIBERATELY KEPT, 2026-09-25 (COMPOSEPUB). The owner
  //     vacation directive's section 1 commissions publishing the composed
  //     caches, so this clause was the thing to check rather than inherit.
  //     Two windows were NOT opened and the decision record is
  //     `spec/memory_rules.md` 5b: COMPOSED_HEIGHT's lattice already reaches
  //     four consumers THROUGH FABRIC -- zhao_terrain_patch's `top_o` streams
  //     into zhao_terrain_compcache_front, which serves TERRAIN.TESS,
  //     TERRAIN.HEIGHTTAP and through TAPSHARE both PART.COLLIDE and
  //     FORGE.SHADOW -- so a writer here would be read by NOTHING, and
  //     COMPOSED_VELOCITY has no consumer at any level (efa_velocity
  //     dead-ends; zhao_terrain_velocity is instantiated only in the fit
  //     harness). Charging the write with tools/budget/sdram_bandwidth.py
  //     --with-composed-publish also takes the frame from 80.17% to 124.41%
  //     at the FLATTERING hit spans. So the clause above stands for the
  //     reason TERRAIN.DEVSTORE's own enactment gives six days earlier:
  //     "a window opened WITH its block, never ahead of it."
  //
  //     TERRAIN.PAGELOADER writes pages and nothing else;
  //     TERRAIN.WRITEBACK reads sheets out of those same pages and nothing
  //     else. In particular WRITEBACK_STAGING/journal at 0x0578_0000 stays
  //     unmapped: v1's writeback goes straight across MEM.HPS.BRIDGE, so
  //     opening it would be a hole with a plan attached.
  //   * ONE client. Only ZHAO_CLIENT_TERRAIN_BUILD reaches it (the case arm
  //     below); ENGINE1 does not, DEBUG does not, and the framebuffer writers
  //     do not.
  //   * TWO DIRECTIONS, TWO ARMS, ONE WINDOW. `terrain_ok` REQUIRES
  //     `req.write`; `terrain_rd_ok` REQUIRES `!req.write`; the bounds are the
  //     same two constants. The write arm is TERRAIN.PAGELOADER depositing
  //     pages. The read arm is TERRAIN.WRITEBACK evacuating a dirty layer F,
  //     which T2 places INSIDE the page ("no separate permanent E/F/H pools"),
  //     so there IS no F pool to read and the sheet is reachable only here.
  //     Both are ruled traffic for this one client: T3 names page loads AND
  //     F-sheet writeback as TERRAIN_BUILD's, and T4 REQUIRES the writeback.
  //     Client id 5 stays unspent because T3 forbids spending it pre-emptively,
  //     so a second client id for the reader was neither available nor narrower
  //     -- it would have put two clients in one region.
  //
  //     `terrain_ok || terrain_rd_ok` is the window test with the direction bit
  //     factored back out, and one comparison would synthesise identically. The
  //     arms are kept SEPARATE because the PROOF states them separately: two
  //     theorems name WHICH direction regressed, and a merged arm would satisfy
  //     both non-vacuity covers while proving neither.
  //
  //     THE READ WAS WITHHELD UNTIL ITS BLOCK EXISTED, and this comment is
  //     where that promise was made: "when the block that does it exists, it
  //     brings its own arm and its own proof. Admitting the read now would
  //     admit it for a writeback path that has never been written."
  //     `fpga/rtl/terrain/zhao_terrain_writeback.sv` now exists, is registered
  //     in tools/rtl/check_guard_verdict.py's client list, and reads exactly
  //     the 64-byte page header plus the 129 chunks spanning layer F -- 130
  //     requests per sheet, asserted as an exact count by its bench.
  //
  //     A READ CANNOT ALTER A FRAME BUFFER. That is the GEOM.ASSET_POOL
  //     argument and it holds twice over here: a forwarded read carries no
  //     write data at all, and this window's CONSTANT bounds are disjoint from
  //     both framebuffer slots (0x0000_0000 and 0x0200_0000) and from the asset
  //     pool. The widening is confined to bank 2, and the no-escape theorem is
  //     unchanged in meaning -- what changes is one direction bit, for one
  //     client, over one region it already owned.
  //   * CONSTANT BOUNDS. No map input is consulted, so this window is not
  //     frame-scoped and cannot be moved by a grant; BASE + SPAN is
  //     0x054E_0000 exactly, computed at elaboration, so the wrap the blit
  //     clamp exists to prevent cannot arise here.
  //
  // WHAT THIS WINDOW DOES **NOT** DO, SAID OUT LOUD.
  // T2 asks for STATE-AWARE permission -- "a loader may write only a LOADING
  // slot" -- and this is not that. The guard has one muxed request port and no
  // residency context; knowing which slot is LOADING means a 1,024-entry state
  // shadow plus an address-to-slot decode by 21,376 (not a power of two) on the
  // verdict path of the block whose counter enable was already the largest
  // negative-slack family in the composed shell. The interface that would carry
  // that state -- who owns the bitmap, how it crosses to the guard, what a
  // stale copy means -- is NOT ruled anywhere, so it is not invented here.
  //
  // The residual, precisely: a faulty TERRAIN.BUILD may write a page slot other
  // than the one it was told to load. It cannot touch a framebuffer, cannot
  // touch the asset pool, cannot touch the rest of bank 2, and cannot leave the
  // map -- so the no-escape theorem is unchanged and the worst case is corrupt
  // GROUND for one page, caught by the CRC the directory checks before it
  // publishes. TERRAIN.PAGELOADER already refuses an out-of-pool slot itself
  // (its slot index is one bit wider than the pool so the refusal is reachable
  // rather than truncated). Tightening this to the LOADING slot is a separate,
  // ruled piece of work and it needs the residency-to-guard interface first.
  //
  // THE NEW RESIDUAL THE READ ARM CREATES, said out loud like the write one.
  // Client 6 may now read ANY page in the pool, so a faulty writeback could
  // journal ANOTHER PATCH'S scars into the HPS journal. MEM.GUARD cannot see
  // that -- it is the same state-awareness gap as the write side, for the same
  // reason, and it is NOT closed here. It is answered one block up:
  // TERRAIN.WRITEBACK reads the evicted page's 64-byte HEADER FIRST and refuses
  // (`kSheetHeaderIdent`) before a single journal byte moves, if
  // {island_id, patch_ix, patch_iz} does not match the job. That is
  // spec/terrain_rules.md 2.1's "redundancy is a corruption check" spent on
  // exactly the failure this arm creates, and it costs one 64-byte read of 130.
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby
  logic terrain_ok, terrain_rd_ok;
  assign terrain_ok = req.write
                    && (addr32 >= ZHAO_TERRAIN_PAGE_POOL_BASE)
                    && (end32  <= ZHAO_TERRAIN_PAGE_POOL_BASE
                                  + ZHAO_TERRAIN_PAGE_POOL_SPAN);
  // The READ arm. Same two constants, opposite direction bit, deliberately a
  // SEPARATE assign so the two directions stay two theorems.
  assign terrain_rd_ok = !req.write
                       && (addr32 >= ZHAO_TERRAIN_PAGE_POOL_BASE)
                       && (end32  <= ZHAO_TERRAIN_PAGE_POOL_BASE
                                     + ZHAO_TERRAIN_PAGE_POOL_SPAN);

  // TERRAIN.DEVSTORE: the per-resident-page deviation and history records,
  // owner ruling R242 (2026-09-22) -- "Move deviation store to SDRAM, ignore
  // stale info". A NEW WINDOW -- the SEVENTH by the running count in the
  // comments above (two FB slots, RENDER.ASSET_POOL, TERRAIN.PAGE_POOL, R32's
  // resource arm, POST.ECHO) -- stated plainly for the reasons the terrain
  // page-pool arm gives rather than folded into it.
  //
  // IT IS A SEPARATE WINDOW AND NOT A WIDENING OF THE PAGE POOL, deliberately.
  // The two regions are disjoint and 0x38_0000 apart, so a request cannot walk
  // out of one into the other, and a fault in the record path cannot reach a
  // page's canonical bytes. Folding them into one comparison would have been
  // one gate cheaper and would have made every deviation write a legal page
  // write.
  //
  //   * ONE CLIENT. ZHAO_CLIENT_TERRAIN_BUILD, the same client that already
  //     loads the pages these records are DERIVED FROM. Client id 5 stays
  //     unspent: ruling T3 forbids spending it pre-emptively, and R242
  //     authorised a REGION, not an ABI act. THE RESIDUAL THIS CREATES IS
  //     STATED RATHER THAN LEFT TO BE FOUND: the record READ is frame-critical
  //     (TERRAIN.SPDESC blocks on it) while client 6 is ruling T3's BACKGROUND
  //     class, below every guaranteed client. A frame in which page loads
  //     saturate the socket therefore delays LOD decisions. That is a
  //     PRIORITY question for the arbiter, not a containment question for this
  //     block, and `zhao_terrain_devstore`'s `rd_wait_clocks_o` is where it
  //     becomes visible instead of being argued.
  //   * TWO DIRECTIONS, TWO ARMS, ONE WINDOW -- the page pool's discipline,
  //     copied. `devstore_wr_ok` REQUIRES `req.write` (the mip pass depositing
  //     a page's sixteen records, and the LOD pass writing the patch's history
  //     row back); `devstore_rd_ok` REQUIRES `!req.write` (the LOD pass
  //     reading them). The bounds are the same two constants. The arms are
  //     SEPARATE assigns because the PROOF states them separately: two
  //     theorems name WHICH direction regressed, and a merged arm would
  //     satisfy both non-vacuity covers while proving neither.
  //   * CONSTANT BOUNDS, HALF-OPEN, OVERFLOW-SAFE. BASE + SPAN is 0x058B_0000
  //     exactly, computed at elaboration; `end32` is a 32-bit sum of a 27-bit
  //     address and a 7-bit length, so it cannot wrap. No map input is
  //     consulted, so this window is not frame-scoped.
  //   * A REQUEST STRADDLING THE EDGE IS REFUSED WHOLE. `addr >= BASE` and
  //     `end <= BASE + SPAN` are both required, so a burst that begins inside
  //     TERRAIN.DEVSTORE and ends above it fails the second term, and one that
  //     ends inside but begins below fails the first. Lying in the UNION of
  //     two permitted regions is not permission: the page pool's own arms are
  //     evaluated over the page pool's constants and admit nothing here.
  //
  // WHAT THIS WINDOW DOES **NOT** DO, said out loud like the page pool's.
  // It is spatially the WHOLE store, not the one slot a job is working on --
  // the same state-awareness gap, for the same reason (the guard has one muxed
  // request port and no residency context). The residual: a faulty
  // TERRAIN.DEVSTORE could write another resident page's records. It cannot
  // reach a framebuffer, the asset pool, the page pool, the echo buffer or
  // anything outside the map, so the no-escape theorem is unchanged, and the
  // worst case is one page drawn at the wrong LOD -- which
  // `zhao_terrain_devstore`'s `slot_addr_bad_o` watches from inside the block,
  // where the slot the read was STARTED for and the address the burst was
  // ISSUED at are two registers loaded by two different enables.
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby, and the committed
  // mutant tests/mutants/zhao_mem_guard_devbound_mutant.sv (the upper bound
  // removed) that makes that proof FAIL.
  logic devstore_wr_ok, devstore_rd_ok;
  assign devstore_wr_ok = req.write
                        && (addr32 >= ZHAO_TERRAIN_DEVSTORE_BASE)
                        && (end32  <= ZHAO_TERRAIN_DEVSTORE_BASE
                                      + ZHAO_TERRAIN_DEVSTORE_SPAN);
  assign devstore_rd_ok = !req.write
                        && (addr32 >= ZHAO_TERRAIN_DEVSTORE_BASE)
                        && (end32  <= ZHAO_TERRAIN_DEVSTORE_BASE
                                      + ZHAO_TERRAIN_DEVSTORE_SPAN);

  // GEOM.PARAMBUF: the external geometry arena, owner completion ruling
  // ITEM 4 (2026-09-22) over spec/memory_rules.md 5c and ruling R7. The
  // EIGHTH window by the running count in this block's header, and the first
  // one that is THREE disjoint regions rather than one.
  //
  // WHY THREE COMPARISONS AND NOT ONE. Item 4 is explicit: "A request
  // crossing a per-view or scratch boundary is not allowed merely because
  // both endpoints lie somewhere in the union of permitted ranges." The three
  // regions TILE -- view0 ends exactly where view1 begins, view1 ends exactly
  // where the scratch begins, the scratch ends exactly at
  // ZHAO_RENDER_ASSET_BASE -- so a single [VIEW0_BASE, SCRATCH_END)
  // comparison would be arithmetically identical for every request that lies
  // inside any ONE of them, and would ADDITIONALLY admit every request that
  // spans a seam. That is not a corner: the two views exist precisely because
  // one is being written while the other is being read, so a burst from the
  // end of view 0 into the start of view 1 is the producer scribbling on the
  // frame the walker is following. `pb_in_view0`, `pb_in_view1` and
  // `pb_in_scratch` are therefore three separate containment tests and a
  // request must satisfy ONE of them WHOLE.
  // `tests/mutants/zhao_geom_parambuf_union_mutant.sv` is the committed fault
  // that replaces them with the union and makes the extended proof FAIL.
  //
  //   * ONE CLIENT. ZHAO_CLIENT_ENGINE1, and only through the arms below --
  //     item 4: "No other client acquires PARAMBUF access through this
  //     ruling. NO blanket bank-3 permission." Client 5 stays unspent (T3);
  //     TERRAIN_BUILD's four arms are evaluated over TERRAIN's own constants
  //     and admit nothing here.
  //   * THREE ARMS OVER THREE REGIONS, stated separately for the page pool's
  //     reason: a merged arm satisfies every non-vacuity cover while half the
  //     logic is dead, and a regression has to name WHICH half broke.
  //     `pb_rd_ok` REQUIRES `!req.write` and admits EITHER view (the walker
  //     reads the published view; a diagnostic read of the view being built
  //     is still a read and cannot corrupt anything). `pb_wr_ok` REQUIRES
  //     `req.write` AND names the view through `pb_wr_view` -- the only
  //     non-constant bound this window has, and it gets the blit lease's
  //     discipline. `pb_scr_ok` takes BOTH directions inside the scratch,
  //     because a prefetch buffer is written by the fetcher and read by the
  //     walker, and gates on the explicit acquire.
  //   * CONSTANT BOUNDS, HALF-OPEN, OVERFLOW-SAFE. Every BASE + SPAN here is
  //     computed at elaboration and the largest is 0x06A0_0000; `end32` is a
  //     32-bit sum of a 27-bit address and a 7-bit length and cannot wrap.
  //   * ENGINE1'S ASSET-POOL PERMISSION IS UNCHANGED. `render_asset_ok`
  //     still requires `!req.write`, and none of the three arms can be true
  //     inside [0x06A0_0000, 0x0800_0000) because all three regions end at or
  //     below its base. So "RENDER.ASSET_POOL stays READ-ONLY to ENGINE1"
  //     survives this ruling structurally, not by inspection --
  //     a1_pb_asset_still_ro.
  //   * DENY-ALL WHEN THE LEASE IS LOW. All three arms require
  //     `pb_lease_valid`. Tie it low and this window does not exist, which is
  //     what every guard instance outside the console core does.
  //
  // WHAT THIS WINDOW DOES **NOT** DO, said out loud like the page pool's. It
  // is spatially the WHOLE of a view, not the one allocation a job owns
  // inside it -- the guard has one muxed request port and no allocation
  // context. The residual: a faulty ENGINE1 could write another live
  // allocation's records inside the view it already holds. It cannot reach
  // the OTHER view, the scratch it has not acquired, the asset pool, a
  // framebuffer, the terrain regions, the echo capture or anything outside
  // the map, so the no-escape theorem is unchanged. Allocation-level
  // containment is `zhao_geom_paramarena`'s, where the chunk free-list and
  // the reader-ownership bits live, and `arena_overrun_o` watches it from
  // inside the block.
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby, and the committed
  // mutants tests/mutants/zhao_mem_guard_pbview_mutant.sv (the write arm's
  // view selection removed) and zhao_mem_guard_pbunion_mutant.sv (the three
  // containment tests collapsed to their union), each of which makes that
  // proof FAIL.
  logic pb_in_view0, pb_in_view1, pb_in_scratch;
  logic pb_rd_ok, pb_wr_ok, pb_scr_ok;

  // THE THREE REGIONS TILE, AND THE PACKAGE CANNOT SAY SO ITSELF. A
  // SystemVerilog package holds no `initial` block, and R212 measured that
  // Quartus 17.0 rejects a bare module-scope elaboration `if`, so the guard
  // for 5c's constants lives HERE, in the block that reads them, inside
  // `initial begin ... end` -- the form R212 says Quartus accepts.
  //
  // It is a real check and not decoration: if someone moves VIEW1_BASE
  // without moving VIEW_SPAN, the three containment tests above go on
  // compiling, go on passing lint, and leave an UNMAPPED HOLE or an OVERLAP
  // between two regions whose whole purpose is to be disjoint. The hole is
  // harmless and the overlap is the fault this window was written to refuse,
  // and neither is visible in a waveform.
  //
  // CLAUDE.md: `--lint-only` does NOT run `initial` blocks, so a clean lint
  // says nothing whatever about these three lines. They are exercised by
  // elaboration in every Verilator TEST BINARY and by `quartus_map`.
  // synthesis translate_off
  initial begin
    if (ZHAO_PARAMBUF_VIEW0_BASE + ZHAO_PARAMBUF_VIEW_SPAN
        != ZHAO_PARAMBUF_VIEW1_BASE)
      $fatal(1, "zhao_mem_guard: PARAMBUF view 0 does not end where view 1 begins");
    if (ZHAO_PARAMBUF_VIEW1_BASE + ZHAO_PARAMBUF_VIEW_SPAN
        != ZHAO_PARAMBUF_SCRATCH_BASE)
      $fatal(1, "zhao_mem_guard: PARAMBUF view 1 does not end where the scratch begins");
    if (ZHAO_PARAMBUF_SCRATCH_BASE + ZHAO_PARAMBUF_SCRATCH_SPAN
        != ZHAO_RENDER_ASSET_BASE)
      $fatal(1, "zhao_mem_guard: PARAMBUF scratch does not end at RENDER.ASSET_POOL");
  end
  // synthesis translate_on

  assign pb_in_view0   = (addr32 >= ZHAO_PARAMBUF_VIEW0_BASE)
                       && (end32  <= ZHAO_PARAMBUF_VIEW0_BASE
                                     + ZHAO_PARAMBUF_VIEW_SPAN);
  assign pb_in_view1   = (addr32 >= ZHAO_PARAMBUF_VIEW1_BASE)
                       && (end32  <= ZHAO_PARAMBUF_VIEW1_BASE
                                     + ZHAO_PARAMBUF_VIEW_SPAN);
  assign pb_in_scratch = (addr32 >= ZHAO_PARAMBUF_SCRATCH_BASE)
                       && (end32  <= ZHAO_PARAMBUF_SCRATCH_BASE
                                     + ZHAO_PARAMBUF_SCRATCH_SPAN);

  assign pb_rd_ok  = !req.write && pb_lease_valid
                   && (pb_in_view0 || pb_in_view1);
  // THE VIEW IS NAMED, not inferred from the address. `pb_wr_view ?
  // pb_in_view1 : pb_in_view0` refuses a write to the view the lease does not
  // name even though that write is perfectly contained -- which is the whole
  // point, and is why this is a mux and not an `||`.
  // ============ THE MUTATION, AND IT IS THE VIEW SELECTION =================
  // Production admits a WRITE only into the view the lease NAMES. This copy
  // keeps the containment and drops the naming: either view opens, so the
  // producer may write the view the walker is currently reading. That is the
  // exact fault the two-view split exists to prevent, and it is invisible to
  // any test that only ever builds one view.
  /* verilator lint_off UNUSEDSIGNAL */
  wire mut_pb_wr_view_unused = pb_wr_view;
  /* verilator lint_on UNUSEDSIGNAL */
  assign pb_wr_ok  = req.write && pb_lease_valid
                   && (pb_in_view0 || pb_in_view1);
  assign pb_scr_ok = pb_lease_valid && pb_scratch_valid && pb_in_scratch;

  // THE FIFTH WINDOW (R32): a WRITE arm into RENDER.ASSET_POOL for
  // TERRAIN_BUILD, bounded to the published-resource region. Stated as its own
  // window for the reasons the terrain arm gives: one client, one direction,
  // one region -- and the region is the only non-constant bound in this block
  // besides the blit's, so it gets the blit's discipline. The end is computed
  // in 33 bits so `res_base + res_span` cannot wrap, and the region must lie
  // WHOLLY inside the asset pool or the arm is closed: a region straddling a
  // framebuffer is refused whole rather than clamped into something legal-
  // looking. ENGINE1's read arm is untouched, so the asset pool gains a WRITER
  // and keeps its one READER.
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby, and the committed
  // mutant tests/mutants/zhao_mem_guard_resbound_mutant.sv (the pool-
  // containment term removed) that makes that proof FAIL.
  logic [32:0] res_end33, end33;
  logic        res_in_pool, resource_wr_ok;
  assign res_end33   = {1'b0, res_base} + {1'b0, res_span};
  assign end33       = {1'b0, end32};
  assign res_in_pool = res_valid
                     && (res_base  >= ZHAO_RENDER_ASSET_BASE)
                     && (res_end33 <= {1'b0, ZHAO_RENDER_ASSET_BASE + ZHAO_RENDER_ASSET_SPAN});
  assign resource_wr_ok = req.write && res_in_pool
                        && (addr32 >= res_base) && (end33 <= res_end33);

  // ENGINE0 GAINS TWO ARMS, 2026-09-19, and neither opens a way out of the map.
  //
  // 1. `fb_read_ok` -- a READ of the LEASED slot window. POST.COMPOSITE.md: "POST
  //    .COMPOSITE owns an exclusive framebuffer read/write lease after resolve
  //    and before publication". Post runs INSIDE the render lease, after the
  //    raster has drained and before anything publishes, so its identity is the
  //    render engine's own: ENGINE0, under `fb_writer == 1`, inside the SAME
  //    clamped window the render writes go to. No new client id (T3 keeps 5
  //    unspent) and no new window -- a direction bit, for the client that
  //    already owned this window, while it holds the lease. A read cannot alter
  //    a frame buffer, so the no-escape theorem gains nothing to prove.
  //
  // 2. `echo_ok` -- a WRITE of POST.ECHO's capture buffer (ruling R7). A FIFTH
  //    window (SIXTH, counting R32's resource arm), named as one: CONSTANT bounds in bank 2's reserved tail
  //    (zhao_pkg ZHAO_POST_ECHO_BASE, spec/memory_rules.md 5g), disjoint from
  //    both FB slots, the asset pool and the terrain pool, so a capture write
  //    can never alter a displayed or displayable frame. Lease-gated like the
  //    rest of ENGINE0: the echo writes only during a post pass, which only
  //    happens while the renderer holds the lease.
  //
  // ENFORCED-BY: tests/formal/mem_guard_no_escape.sby (a1_region, a1_echo_*,
  //              c_forward_engine_rd, c_forward_echo)
  logic fb_read_ok, echo_ok;
  assign fb_read_ok = !req.write && map_valid
                      && (addr32 >= blit_base) && (end32 <= blit_end);
  assign echo_ok    = req.write
                      && (addr32 >= ZHAO_POST_ECHO_BASE)
                      && (end32  <= ZHAO_POST_ECHO_BASE + ZHAO_POST_ECHO_SPAN);

  // ONE WINDOW, ONE OWNER AT A TIME. Both writers are checked against the same
  // clamped slot span; what separates them is which one the lease names. A
  // writer without the lease is refused exactly as a request outside the window
  // is, and the region this block guarantees nothing escapes is unchanged.
  always_comb begin
    unique case (req.client)
      ZHAO_CLIENT_SCANOUT:  pass_ok = shape_ok && scan_ok;
      ZHAO_CLIENT_BLIT_DMA: pass_ok = shape_ok && blit_ok && (fb_writer == 1'b0);
      ZHAO_CLIENT_ENGINE0:  pass_ok = shape_ok && (blit_ok || fb_read_ok || echo_ok)
                                      && (fb_writer == 1'b1);
      ZHAO_CLIENT_ENGINE1:  pass_ok = shape_ok && (render_asset_ok
                                                   || pb_rd_ok
                                                   || pb_wr_ok
                                                   || pb_scr_ok);
      ZHAO_CLIENT_TERRAIN_BUILD: pass_ok = shape_ok && (terrain_ok || terrain_rd_ok
                                                        || resource_wr_ok
                                                        || devstore_wr_ok
                                                        || devstore_rd_ok);
      default: pass_ok = 1'b0;      // DEBUG still owns nothing, and neither
                                    // does the unspent client 5
    endcase
  end

  // --------------------------------------------------------- forwarding ----
  // a passing request is latched and presented to the arbiter until granted;
  // ready/valid end-to-end: the guard is ready exactly when its forwarding
  // stage is free (an offered request is held upstream, never dropped)
  logic           fwd_active;
  zhao_arb_req_t  fwd_req;

  always_comb begin
    arb_req       = fwd_req;
    arb_req.valid = fwd_active;
  end

  // `rsp` gets exactly ONE kind of driver. Continuously assigning rsp.ready
  // while driving rsp.ok/rsp.violation from the always_ff below mixes a
  // continuous and a procedural driver on one variable, which IEEE 1800
  // forbids (a variable may be written by procedural statements OR by a
  // single continuous assignment, never both) — packed struct fields are not
  // separate variables. Tools that accept it resolve the struct
  // inconsistently: in the elaborated formal model arb_req.valid became
  // unreachable, which silently made the no-escape assertions VACUOUS.
  // The verdict bits are registered here and the whole struct is assembled
  // by this single always_comb.
  logic rsp_ok_q, rsp_violation_q;
  always_comb begin
    rsp.ready     = !fwd_active;   // level; verdict 1 cycle after accept
    rsp.ok        = rsp_ok_q;
    rsp.violation = rsp_violation_q;
  end

  // ------------------------------------------------------------- seq core --
  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      fwd_active          <= 1'b0;
      fwd_req             <= '0;
      rsp_ok_q            <= 1'b0;
      rsp_violation_q     <= 1'b0;
      guard_violation     <= 1'b0;
      guard_violations    <= 32'd0;
      guard_violation_req <= '0;
    end else begin
      // defaults: one-cycle verdict pulses
      rsp_ok_q         <= 1'b0;
      rsp_violation_q  <= 1'b0;
      guard_violation  <= 1'b0;

      // THE COUNTER FOLLOWS THE PULSE, NOT THE DECISION.
      //
      // `guard_violations` used to increment in the same cycle as the verdict,
      // which put the whole range-check chain -- the requester's address, the
      // end address, four bounds compares, the client case -- on the ENABLE of
      // a 32-bit register bank. The full negative-slack census made it the
      // largest remaining family in the composed shell:
      //
      //   1,383 paths  scanout|fetch -> mem_guard|guard_violations   -0.195
      //
      // It counts the same events either way. `guard_violation` is already the
      // registered one-cycle pulse for exactly this verdict, so counting off
      // IT costs one cycle of latency on an observability counter and takes
      // the comparison chain off the counter entirely.
      //
      // The SAFETY path is untouched: rsp_ok_q, rsp_violation_q, fwd_active
      // and fwd_req still resolve in the accepting cycle, which is what
      // tests/formal/mem_guard_no_escape.sby proves about.
      if (guard_violation) guard_violations <= guard_violations + 32'd1;

      // forwarded request leaves when the arbiter accepts it
      if (fwd_active && arb_rsp.grant) fwd_active <= 1'b0;

      // accept at most one request per cycle (rsp.ready level above)
      if (req.valid && !fwd_active) begin
        if (pass_ok) begin
          rsp_ok_q          <= 1'b1;
          fwd_active        <= 1'b1;
          fwd_req.write     <= req.write;
          fwd_req.client    <= req.client;
          fwd_req.addr      <= req.addr;
          fwd_req.len       <= req.len;
        end else begin
          rsp_violation_q     <= 1'b1;
          guard_violation     <= 1'b1;
          guard_violation_req <= req;   // full request traced to the harness
        end
      end
    end
  end

  // arb_rsp.credits is not consumed here (the guard is request-path only;
  // the arbiter owns credit law) — keep the frozen port type and silence
  // the field-unused lint.
  /* verilator lint_off UNUSEDSIGNAL */
  logic [7:0] unused_arb_credits;
  assign unused_arb_credits = arb_rsp.credits;
  /* verilator lint_on UNUSEDSIGNAL */

endmodule
