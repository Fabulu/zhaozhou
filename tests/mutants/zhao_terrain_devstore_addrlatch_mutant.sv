// ===========================================================================
// zhao_terrain_devstore.sv -- TERRAIN.LOD's PER-PAGE DEVIATION AND HISTORY
// STORE.  Owner rulings R24, R59 and R242.
//
// ===========================================================================
// WHAT IT IS FOR
// ===========================================================================
// `zhao_terrain_lod` needs three things per subpatch that it deliberately does
// not keep: the three stored coarse-level deviations (`sp_dev1/2/3_i`) and the
// previous frame's history (`sp_prev_level_i`, `sp_prev_morph_i`, `sp_hold_i`).
// Its own law 5 says so in as many words -- "THE HISTORY RIDES THE PACKET ...
// for the caller to store.  REJECTED: an internal history RAM" -- and the
// entry I21 in `zhao_console_core.sv` records the consequence: the only driver
// of `sp_dev1_i` in this tree was an LFSR in `zhao_prod_top`.
//
// `zhao_terrain_loddev` (owner ruling R8) is the producer of the deviations.
// This block is the store between them, and it is a store and not a wire for
// the reason ruling R24 gives: the deviations are computed AT PAGE LOAD and
// consumed PER FRAME, so something has to hold them across the gap.
//
// ===========================================================================
// RULING R242 -- THE MEDIUM CHANGED ON 2026-09-22, AND ONLY THE MEDIUM
// ===========================================================================
//   Fabian, 2026-09-22: "Move deviation store to SDRAM, ignore stale info."
//
// The stale info is ruling R24's STORAGE CLAUSE -- "At PAGE LOAD, stored
// alongside the page in M10K (the owner prefers M10K over ALMs)".  That
// preference was correct when it was made, because M10K was the resource with
// slack.  Ruling R87 ended that: "against 306 of 553 already used, one block
// wanting 185 is not a rounding error... Price M10K explicitly in the fit
// plan; it is no longer the free currency."
//
// EVERYTHING ELSE R24 DECIDED STANDS, AND EACH IS STILL LOAD-BEARING HERE:
//
//   * the deviations are computed AT PAGE LOAD, not per frame.  That is not a
//     preference, it is measured: `zhao_terrain_loddev` spends about 13,700
//     clocks on one patch's one surface (16 subpatches x {56, 72, 77} measured
//     vertices x 4 clocks, plus the skipped slots at one).
//     `spec/terrain_rules.md` 4.2 puts 256 live/visible patches in a frame and
//     the frame is 1.67M gpu clocks, so recomputing the visible set is ~3.5M
//     clocks -- TWICE THE FRAME, before anything is drawn.
//   * THE KEY IS THE RESIDENCY PAGE SLOT.  A compose slot is reused by a
//     different patch from one frame to the next, so the HISTORY -- which is
//     what hysteresis is made of -- would be inherited by a stranger.  The
//     addressing below is `slot`, and nothing else.
//   * BAKE RE-TRIGGERS THE RECOMPUTE for the pages it dirties, and arrives
//     here as `inv_valid_i`.
//
// WHAT THE OWNER GETS BACK: 185 M10K, 33% of the device.  141 for the
// deviations (2,048 rows x 704) and 44 for the history (1,024 x 432).  Neither
// array exists any more; this block now infers NO MEMORY AT ALL.
//
// WHAT IT COSTS: 320 KiB of local SDRAM in bank 2's reserved tail, and the
// flops for one 64-byte burst in each direction.  The flop delta is counted in
// THE PRICE OF THE MOVE below, in the unflattering direction.
//
// ===========================================================================
// THE LAYOUT, DERIVED FROM THE PARAMETERS AND NEVER FROM PROSE
// ===========================================================================
// >> EVERY NUMBER IN THIS BLOCK'S SIZING SECTION WAS WRONG UNTIL 2026-09-20,
// >> AND WRONG IN THE FLATTERING DIRECTION.  The record gained a 16-bit
// >> subpatch centre height (`RECW = 3*DEVW + 16`, 88 bits) after the section
// >> was written, and the two localparams DERIVED from it kept their old
// >> comments: `ROWW` said 576 when the parameters said 704.  The prose then
// >> computed the store's price from 72-bit records and published 116 M10K
// >> against a real 141.  RULING R59'S OWN PREMISE WAS THE SAME ERROR ONE STEP
// >> FURTHER BACK: it priced this store at "~786 kbit = ~77 M10K of 553 (14%)"
// >> using a 16-bit deviation where `DEVW` is 24, and counting no history at
// >> all -- 2.4x the figure the ruling was decided against.  "14% is affordable
// >> and 33% is an argument, which is exactly why nobody audited it."
// >>
// >> So every constant below is a localparam computed from a parameter, and
// >> `tools/design/check_localparam_comments.py` watches the comments on them.
// >> The arithmetic is spelled out term by term because it cannot watch prose.
//
// ONE SLOT OWNS 320 BYTES, IN TWO SUB-POOLS:
//
//   deviations   DEV_BASE  + slot * 256, four 64-byte bursts
//                  a record is 3*DEVW + 16 = 88 bits, PADDED TO 128 (16 B)
//                  16 records x 16 B = 256 B
//   history      HIST_BASE + slot * 64, ONE 64-byte burst
//                  2 + MORPHW + 8 = 27 bits x 16 = 432 bits = 54 B, padded
//
//   footprint    1,024 x (256 + 64) = 327,680 B = 320 KiB = zhao_pkg's
//                ZHAO_TERRAIN_DEVSTORE_SPAN, checked at elaboration.
//
// WHY THE RECORD IS PADDED 88 -> 128 AND THE PADDING IS NOT WASTE.  A packed
// 88-bit record makes a patch 176 B, which is 2.75 bursts: records 5/6 and
// 11/12 would STRADDLE burst boundaries, the staging register on each side
// would have to be the whole 176 B (1,408 flops), and every burst boundary
// would be a place to get a shift wrong.  At 16 B a 64-byte burst is EXACTLY
// four records, the staging is 512 bits, and no record is ever split.  ALMs
// are the binding constraint on this device and SDRAM here is not: the padding
// buys 896 flops for 80 KiB of a reserved region.
//
// AND THE PADDING IS *NOT* THE 67-BIT PACKING, WHICH STAYS REFUSED.  A further
// 33 M10K used to be available by packing records at 67 bits, because every
// lattice height reaching `zhao_terrain_loddev` today is `height16 << 8` so
// every deviation's low seven bits are provably zero.  R242 keeps the refusal
// and so does this file: "the invariant is upstream, unenforced and invisible:
// the moment a composed height carries a FIELD delta (entry I34's lane) the
// low bits stop being zero and every deviation silently quantises to 128ths
// with no counter able to see it."  Padding UP cannot be wrong in that way.
//
// ===========================================================================
// THE GUARDED REGION, AND THE DISCIPLINE THAT CAME WITH IT
// ===========================================================================
// R242 authorised the region as "a smaller instance of the 2026-09-22 item 4
// act".  `zhao_mem_guard.sv` carries it as `devstore_wr_ok` / `devstore_rd_ok`
// -- ONE window, TWO arms, CONSTANT bounds, TERRAIN_BUILD alone, with a
// half-open extent test that refuses a straddling burst WHOLE.  Client id 5
// stays unspent (ruling T3).  `tests/formal/mem_guard_no_escape.sby` proves
// it with a cover per direction, and `tests/mutants/
// zhao_mem_guard_devbound_mutant.sv` is the deliberate fault that makes that
// proof fail.
//
// THE REQUEST IDENTITY TRAVELS WITH THE REQUEST, which is this repository's
// own worst defect stated as a rule.  A metadata bank once registered its read
// UNCONDITIONALLY and delivered response A's data with B's metadata, every
// counter balancing, while a live mismatch detector read zero because both
// operands moved in lockstep.  So:
//
//   * `m_addr_q` is LATCHED when the engine takes an op and is the only thing
//     `guard_req_o.addr` is driven from.  No live slot input reaches the guard
//     request, and no queued request is ever re-validated against a later view
//     of `r_slot_i` or `w_slot_i`.
//   * `slot_addr_bad_o` differences the address the ENGINE is holding against
//     the address the READ FSM would compute for the patch it is serving.
//     THE TWO SIDES ARE LOADED BY DIFFERENT ENABLES -- `m_addr_q` at op start
//     by the engine, `r_slot_q`/`r_burst_q` at `r_start_i` and at each burst
//     advance by the read FSM -- so this is not the lockstep-blind kind of
//     check.  It is also NOT REACHABLE with legal stimulus, which is why
//     `tests/mutants/zhao_terrain_devstore_addrlatch_mutant.sv` exists: a copy
//     that loads `m_addr_q` once and never reloads it, with an inverted driver
//     that passes when the counter FIRES.
//   * `stray_beat_o` counts a read beat offered while no read is in flight.
//     That is the check the address round trip CANNOT do: the share broadcasts
//     beat data to every requester and demuxes only `beat_valid`, so a wrong
//     demux delivers another client's bytes.  Beat COUNT is what sees it.
//   * `short_burst_o` counts a burst that ended before its eighth beat.
//
// THE GUARD ANSWERS IN TWO CYCLES AND THE TWO BITS ARE NEVER BOTH HIGH.
// `zhao_mem_guard` drives `rsp.ready = !fwd_active` as a LEVEL and pulses
// `rsp.ok` the cycle AFTER it accepts.  Testing them in one arm reads every
// pass as a denial, silently, with the denial counter stuck at zero -- the
// defect found in BOTH geometry fetchers on 2026-09-06.  So M_REQ waits on
// `ready` and M_VERD, a separate state one cycle later, reads `ok`/`violation`.
// That is `zhao_terrain_pageio.sv`'s law, copied deliberately.
//
// ONE REQUEST SHAPE AND NOTHING ELSE: 64-byte aligned address, len 64, be all
// ones.  The guard REFUSES a sparse `.be` (`be_ok = (req.be == mask_of(len))`)
// and `zhao_vram_arbiter` converts len to WORDS and never sees a byte mask at
// all, so a sparse `be` is a violation rather than an optimisation.  Both
// sub-pools are 64-byte aligned and both strides are multiples of 64, so no
// request this block can construct straddles the sub-pool boundary.
//
// ===========================================================================
// WHAT AN UNWRITTEN SLOT ANSWERS, AND WHY IT IS NOT ZERO
// ===========================================================================
// A patch can be served before its deviations exist -- the mip pass and the
// compose pass are independent, and ruling R24's BAKE re-trigger makes a
// resident page's records momentarily stale by design.  Zero is the WRONG
// answer: `dev = 0` passes every rung of `zhao_terrain_lod`'s ladder, so the
// patch would be drawn at level 3, the coarsest, and mush is indistinguishable
// from distance.  This block answers DEV_MAX instead (every ladder rung fails,
// the patch is drawn at full detail) and COUNTS it on `read_unwritten_o`.  The
// cost of the fail-safe is triangles; the cost of the other one is a wrong
// picture nobody can attribute.
//
// A GUARD DENIAL OR A MALFORMED BURST TAKES THE SAME EXIT, and that is a
// decision rather than a fallthrough.  The alternative -- abandoning the patch
// read -- would leave `r_valid_o` low forever for a consumer that is waiting on
// it, so a memory fault would present as a HANG in `zhao_terrain_spdesc`.
// Degrading to "this slot has no records" keeps the stream's shape exactly,
// costs triangles, and is counted on `guard_denied_o` / `short_burst_o` beside
// `read_unwritten_o` so the two causes are never confused.
//
// THE PER-SLOT VALID BITS ARE FLOPS (1,024 of them) and not a memory, because
// they are read and written on different cycles from the payload and a 1-bit
// M10K would cost a whole block for 1,024 bits.  Under R242 they carry a
// second job: SDRAM CANNOT BE PRESUMED ZERO.  M10K in Verilator is, which hid
// this; local SDRAM after reset holds whatever it holds.
//
// AND THE HISTORY GAINS ITS OWN VALID BANK, WHICH CLOSES A REAL HOLE.  Before
// this pass `hist_mem` had no reset and `inv_valid_i` cleared only
// `slot_valid_q`, so a residency slot reclaimed by a DIFFERENT page served the
// previous page's `prev_level`, `prev_morph` and `hold` -- precisely the
// stranger-inherits-the-hysteresis failure ruling R24's key is chosen to
// prevent, one level down.  `hist_valid_q` is cleared at reset and on every
// invalidation and set when a history row is committed; a read with it clear
// answers the neutral triple {level 0, morph 0, hold 0} and counts
// `hist_unwritten_o`.  Clearing it on a BAKE as well as on a claim costs one
// frame of hysteresis for a patch whose deviations the same bake has just
// invalidated -- so that patch is being drawn at full detail that frame
// anyway, and the conservative direction is the cheap one.
//
// ===========================================================================
// THE COUNTERS AND HOW EACH ONE IS FIRED
// ===========================================================================
// `read_unwritten_o`  a read of a slot with no committed records.  Fired by
//                     reading slot 3 before writing it.
// `hist_unwritten_o`  a read of a slot with no committed history.  Fired the
//                     same way; SILENT once the history has been written back,
//                     which is the negative control.
// `hist_step_bad_o`   the writeback out of step with the descriptor stream.
//                     This is the one CLAUDE.md's "detector wired to two
//                     operands that move together" rule is about.  The read
//                     side walks sp 0..15 off `r_ptr_q` and the writeback walks
//                     sp 0..15 off `h_ptr_q`, and they are SEPARATE counters
//                     advanced by SEPARATE handshakes.  If the two pointers
//                     were one register the check could not fail and would be
//                     worth nothing.  Fired by a seventeenth history record.
// `guard_denied_o`    the guard refused a request.  Fired by a played guard
//                     configured to deny.
// `short_burst_o`     a read burst ended before its eighth beat.  Fired by a
//                     played guard configured to truncate.
// `stray_beat_o`      a read beat arrived with no read in flight.  Fired by
//                     the bench injecting one.
// `slot_addr_bad_o`   the engine's held address is not the address this patch
//                     and burst require.  UNREACHABLE with legal stimulus --
//                     see the committed mutant named above.
//
// Conservative SystemVerilog subset (charter 2).
// Lint gate: lint_terrain_devstore.
`default_nettype none

module zhao_terrain_devstore_addrlatch_mutant
  import zhao_pkg::*;
#(
    // The residency's slot count.  T9/T10's 256 sets x 4 ways.
    parameter int unsigned SLOTS  = 1024,
    parameter int unsigned SLOTW  = 10,
    // `zhao_terrain_loddev`'s deviation width and `zhao_terrain_lod`'s morph.
    parameter int unsigned DEVW   = 24,
    parameter int unsigned MORPHW = 17,
    // WHERE THE STORE LIVES.  Defaults to zhao_pkg's constant; it is a KNOB
    // and the composition site passes the same value explicitly so the region
    // has ONE address authority rather than a default nobody reads.
    parameter logic [26:0] REGION_BASE = ZHAO_TERRAIN_DEVSTORE_BASE[26:0]
) (
    input  var logic clk,
    input  var logic rst_n,

    // WHICH CLIENT IDENTITY THE REQUESTS CARRY.  The upstream share
    // (`zhao_mem_share_wr`) stamps TERRAIN_BUILD's privilege, so this is the
    // block's claim and not its authority -- the same shape
    // `zhao_terrain_pageio` uses, and the reason it is an input rather than a
    // literal is that a block which hard-codes its own privilege cannot be
    // tested against a guard that refuses it.
    input  var zhao_client_e cfg_vram_client_i,

    // ---- WRITE: `zhao_terrain_loddev`'s records, one patch at a time -------
    // Records arrive in subpatch order 0..15.  A burst is committed on every
    // fourth record (3, 7, 11, 15); the slot becomes valid when 15's burst is
    // accepted by the memory system, not when the record arrives.
    input  var logic             w_valid_i,
    output var logic             w_ready_o,
    input  var logic [SLOTW-1:0] w_slot_i,
    input  var logic [3:0]       w_sp_i,
    input  var logic [DEVW-1:0]  w_dev1_i,
    input  var logic [DEVW-1:0]  w_dev2_i,
    input  var logic [DEVW-1:0]  w_dev3_i,
    input  var logic signed [15:0] w_cy_i,     // subpatch centre height16
    output var logic             w_patch_done_o,   // pulse: sp 15 committed

    // ---- INVALIDATE: the page in this slot changed (claim, or a bake) ------
    input  var logic             inv_valid_i,
    input  var logic [SLOTW-1:0] inv_slot_i,

    // ---- READ: one patch's sixteen descriptors, in subpatch order ---------
    input  var logic             r_start_i,
    input  var logic [SLOTW-1:0] r_slot_i,
    output var logic             r_ready_o,        // a start may be taken
    output var logic             r_valid_o,
    input  var logic             r_ready_i,
    output var logic [3:0]       r_sp_o,
    output var logic [DEVW-1:0]  r_dev1_o,
    output var logic [DEVW-1:0]  r_dev2_o,
    output var logic [DEVW-1:0]  r_dev3_o,
    output var logic signed [15:0] r_cy_o,
    output var logic [1:0]       r_prev_level_o,
    output var logic [MORPHW-1:0] r_prev_morph_o,
    output var logic [7:0]       r_hold_o,
    output var logic             r_fresh_o,        // this patch had records

    // ---- HISTORY WRITEBACK: `zhao_terrain_lod`'s decisions, same order ----
    input  var logic              h_valid_i,
    output var logic              h_ready_o,
    input  var logic [1:0]        h_level_i,
    input  var logic [MORPHW-1:0] h_morph_i,
    input  var logic [7:0]        h_hold_i,

    // ---- THE GUARD SOCKET (owner ruling R242) -----------------------------
    // One request shape: 64-byte aligned, len 64, be all ones.  Beat data is
    // BROADCAST by the share and only `beat_valid_i` is demuxed, which is the
    // law `zhao_terrain_pageio` and `zhao_terrain_pagestream` already work
    // under -- and the reason `stray_beat_o` exists.
    output var zhao_guard_req_t guard_req_o,
    input  var zhao_guard_rsp_t guard_rsp_i,
    input  var logic            beat_valid_i,
    input  var logic [63:0]     beat_data_i,
    input  var logic            beat_last_i,
    output var logic [63:0]     guard_wdata_o,
    output var logic            guard_wvalid_o,
    input  var logic            guard_wready_i,
    output var logic            guard_wlast_o,

    // ---- evidence ---------------------------------------------------------
    output var logic [31:0] records_written_o,
    output var logic [31:0] patches_committed_o,
    output var logic [31:0] patches_read_o,
    output var logic [31:0] read_unwritten_o,   // served before its records
    output var logic [31:0] hist_unwritten_o,   // served before its history
    output var logic [31:0] hist_step_bad_o,    // writeback out of step
    output var logic [31:0] invalidations_o,
    output var logic [31:0] guard_denied_o,     // the guard refused a request
    output var logic [31:0] short_burst_o,      // a read burst ended early
    output var logic [31:0] stray_beat_o,       // a beat with no read in flight
    output var logic [31:0] slot_addr_bad_o,    // held address != required one
    output var logic [31:0] bursts_read_o,
    output var logic [31:0] bursts_written_o,
    output var logic [31:0] rd_wait_clocks_o,   // clocks a patch read spent
                                                // waiting on memory
    output var logic        busy_o
);

  // ---- the shape, every constant derived from a parameter -----------------
  localparam int unsigned SUBS      = 16;
  // A record is the three deviations plus the subpatch CENTRE HEIGHT.  The
  // centre is what zhao_terrain_lod measures its camera distance to, and its
  // x and z come free from TERRAIN.PLACE's placed column/row stream -- only
  // the HEIGHT has to be remembered, because the lattice it was read from is
  // gone by the time the patch is served.  height16, 16 bits, the page's own
  // unit.
  localparam int unsigned RECW      = 3 * DEVW + 16;          // 88
  // The STORED record, padded so four fit a burst exactly.  See the header:
  // the padding buys 896 flops of staging, and padding UP can never make a
  // deviation quantise the way the refused 67-bit packing would.
  localparam int unsigned REC_BITS  = 128;
  localparam int unsigned REC_BYTES = REC_BITS / 8;           // 16
  localparam int unsigned BURST_B   = 64;                     // the one shape
  localparam int unsigned BURST_W   = 8 * BURST_B;            // 512 bits
  localparam int unsigned BEATS     = BURST_B / 8;            // 8 x 64-bit
  localparam int unsigned RECS_PB   = BURST_B / REC_BYTES;    // 4 per burst
  localparam int unsigned DEV_BURSTS  = SUBS / RECS_PB;       // 4
  localparam int unsigned DEV_SLOT_B  = SUBS * REC_BYTES;     // 256
  localparam int unsigned HISTW       = 2 + MORPHW + 8;       // 27
  localparam int unsigned HROWW       = SUBS * HISTW;         // 432
  localparam int unsigned HIST_SLOT_B = BURST_B;              // 64, one burst
  // The accumulator holds the THREE records before the one that completes a
  // burst; the fourth is merged on its own cycle rather than stored and read
  // back, so there are REC_BITS fewer flops and one fewer state.
  localparam int unsigned ACCW        = BURST_W - REC_BITS;   // 384

  localparam logic [31:0] DEV_BASE_32  = {5'b0, REGION_BASE};
  localparam logic [31:0] HIST_BASE_32 = DEV_BASE_32 + 32'(SLOTS * DEV_SLOT_B);
  localparam logic [31:0] FOOTPRINT_32 = 32'(SLOTS * (DEV_SLOT_B + HIST_SLOT_B));

  localparam logic [DEVW-1:0] DEV_MAX = {DEVW{1'b1}};

  // Quartus 17.0 rejects a module-scope `if` guard; qualify inside `initial`.
  // NOTE that `--lint-only` does NOT run these, so a clean lint says nothing
  // whatever about them -- they fire in the first simulation that elaborates
  // the block, which is what caught `SLOTS != 1 << SLOTW` in the console smoke
  // when the composer keyed this store on the one-bit-wider memslot.
  // synthesis translate_off
  initial begin
    if (SLOTS != (1 << SLOTW))
      $fatal(1, "zhao_terrain_devstore: SLOTS must be 1 << SLOTW");
    if (DEVW < 8 || DEVW > 32)
      $fatal(1, "zhao_terrain_devstore: DEVW out of range");
    if (RECW > REC_BITS)
      $fatal(1, "zhao_terrain_devstore: RECW exceeds the padded record");
    if (HROWW > BURST_W)
      $fatal(1, "zhao_terrain_devstore: the history row exceeds one burst");
    if (REGION_BASE[5:0] != 6'd0)
      $fatal(1, "zhao_terrain_devstore: REGION_BASE must be 64-byte aligned");
    // `r_burst_q` and `w_burst_q` are TWO BITS.  A parameterisation that made
    // a patch more than four bursts would truncate them silently, which is the
    // shape of fault that arrives as "the terrain is mush" rather than as a
    // message.
    if (DEV_BURSTS != 4)
      $fatal(1, "zhao_terrain_devstore: the burst counters are 2 bits wide");
    // The footprint must fit the region MEM.GUARD actually opens.  A store
    // parameterised past its window would be refused request by request, with
    // the failure arriving as "the terrain is mush" rather than as this line.
    if (FOOTPRINT_32 > ZHAO_TERRAIN_DEVSTORE_SPAN)
      $fatal(1, "zhao_terrain_devstore: footprint exceeds the guarded span");
    if ({1'b0, DEV_BASE_32} + {1'b0, FOOTPRINT_32} > 33'h1_0000_0000)
      $fatal(1, "zhao_terrain_devstore: REGION_BASE + footprint wraps 32 bits");
  end
  // synthesis translate_on

  // ---- addressing ---------------------------------------------------------
  // Both strides are powers of two, so both are shifts and neither needs a
  // multiplier or a divide on any path.  That is why the sub-pools are laid
  // out slot-major rather than interleaved.
  // The sum is formed at 32 bits and truncated to the guard request's 27, and
  // the top five bits are DELIBERATELY dropped rather than checked here: the
  // elaboration guard above refuses a REGION_BASE whose footprint could reach
  // them, so a live 32-bit check would be a comparison that can never be true
  // sitting on the address path of a per-frame read.
  /* verilator lint_off UNUSEDSIGNAL */
  function automatic logic [26:0] dev_addr(input logic [SLOTW-1:0] s,
                                           input logic [1:0] b);
    logic [31:0] t;
    begin
      t = DEV_BASE_32
          + ({{(32 - SLOTW) {1'b0}}, s} << $clog2(DEV_SLOT_B))
          + ({30'b0, b} << $clog2(BURST_B));
      dev_addr = t[26:0];
    end
  endfunction

  function automatic logic [26:0] hist_addr(input logic [SLOTW-1:0] s);
    logic [31:0] t;
    begin
      t = HIST_BASE_32 + ({{(32 - SLOTW) {1'b0}}, s} << $clog2(HIST_SLOT_B));
      hist_addr = t[26:0];
    end
  endfunction
  /* verilator lint_on UNUSEDSIGNAL */

  // ==========================================================================
  // THE MEMORY ENGINE -- one guard socket, two internal customers
  // ==========================================================================
  // The read FSM has PRIORITY over the write FSM, and the reason is a
  // schedule and not a preference: the read is what `zhao_terrain_spdesc`
  // blocks on inside the frame, while the write is a page-load record arriving
  // roughly every 800 clocks with a whole burst of slack behind it.  Neither
  // starves.  The write can always start, because the read FSM stops asking
  // the moment a burst lands (it spends at least four accepted descriptors in
  // R_STREAM), and the read waits at most one burst for a write already in
  // flight.  `rd_wait_clocks_o` measures what that actually costs instead of
  // leaving it as this paragraph's assertion.
  typedef enum logic [2:0] {
    M_IDLE, M_REQ, M_VERD, M_RBEAT, M_WBEAT
  } mstate_e;
  mstate_e          mstate_q;
  logic [26:0]      m_addr_q;
  logic             m_write_q;
  logic             m_owner_rd_q;     // the op belongs to the READ FSM
  logic [BURST_W-1:0] m_rbuf_q;
  logic [BURST_W-1:0] m_wsh_q;
  logic [2:0]       m_beat_q;
  logic             m_done_q;         // pulse: op finished cleanly
  logic             m_fail_q;         // pulse: op finished badly

  // ---- read FSM -----------------------------------------------------------
  typedef enum logic [2:0] {
    R_IDLE, R_HREQ, R_HWAIT, R_DREQ, R_DWAIT, R_STREAM, R_HWR, R_HWRW
  } rstate_e;
  rstate_e            rstate_q;
  logic [SLOTW-1:0]   r_slot_q;
  logic [1:0]         r_burst_q;
  logic [3:0]         r_ptr_q;        // 0..15, the descriptor being offered
  logic [3:0]         h_ptr_q;        // 0..15, the history record being taken
  logic               r_fresh_q;
  logic               r_hfresh_q;
  logic               h_any_q;        // at least one writeback this patch
  logic [BURST_W-1:0] r_row_q;
  logic [HROWW-1:0]   r_hist_q;
  logic [HROWW-1:0]   h_acc_q;

  // ---- write FSM ----------------------------------------------------------
  typedef enum logic [1:0] { W_IDLE, W_REQ, W_WAIT } wstate_e;
  wstate_e            wstate_q;
  logic [ACCW-1:0]    w_acc_q;
  logic [BURST_W-1:0] w_out_q;
  logic [SLOTW-1:0]   w_slot_q;
  logic [1:0]         w_burst_q;
  logic               w_last_q;       // this burst completes the patch
  logic               w_slot_held_q;

  logic [SLOTS-1:0]   slot_valid_q;
  logic [SLOTS-1:0]   hist_valid_q;

  // ---- the internal request lines -----------------------------------------
  logic        rq_v_c, rq_w_c;
  logic [26:0] rq_a_c;
  logic [BURST_W-1:0] rq_d_c;

  always_comb begin
    rq_v_c = 1'b0;
    rq_w_c = 1'b0;
    rq_a_c = 27'd0;
    rq_d_c = '0;
    case (rstate_q)
      R_HREQ: begin
        rq_v_c = 1'b1;
        rq_a_c = hist_addr(r_slot_q);
      end
      R_DREQ: begin
        rq_v_c = 1'b1;
        rq_a_c = dev_addr(r_slot_q, r_burst_q);
      end
      R_HWR: begin
        rq_v_c = 1'b1;
        rq_w_c = 1'b1;
        rq_a_c = hist_addr(r_slot_q);
        rq_d_c = {{(BURST_W - HROWW) {1'b0}}, h_acc_q};
      end
      default: ;
    endcase
  end

  logic        wq_v_c;
  logic [26:0] wq_a_c;
  assign wq_v_c = (wstate_q == W_REQ);
  assign wq_a_c = dev_addr(w_slot_q, w_burst_q);

  // The arbiter.  ONE grant per cycle, read first, and the grant is what
  // LATCHES the address -- nothing downstream ever re-reads `r_slot_q` or
  // `w_slot_q` to build a request that is already in flight.
  logic mo_start_c, mo_rd_c;
  assign mo_start_c = (mstate_q == M_IDLE) && (rq_v_c || wq_v_c);
  assign mo_rd_c    = rq_v_c;

  logic rd_ack_c, rd_fail_c, wr_ack_c, wr_fail_c;
  assign rd_ack_c  = m_done_q &&  m_owner_rd_q;
  assign rd_fail_c = m_fail_q &&  m_owner_rd_q;
  assign wr_ack_c  = m_done_q && !m_owner_rd_q;
  assign wr_fail_c = m_fail_q && !m_owner_rd_q;

  // ---- the guard request, driven ONLY from the latched op -----------------
  always_comb begin
    guard_req_o        = '0;
    guard_req_o.valid  = (mstate_q == M_REQ);
    guard_req_o.write  = m_write_q;
    guard_req_o.client = cfg_vram_client_i;
    guard_req_o.addr   = m_addr_q;
    guard_req_o.len    = 7'(BURST_B);
    guard_req_o.be     = '1;
  end

  assign guard_wvalid_o = (mstate_q == M_WBEAT);
  assign guard_wdata_o  = m_wsh_q[63:0];
  assign guard_wlast_o  = (m_beat_q == 3'(BEATS - 1));

  // THE ADDRESS ROUND TRIP.  What the READ FSM says this op must be, computed
  // from its own registers, against what the ENGINE is holding.  Two registers,
  // two enables, two arithmetic paths; see the header for what it can and
  // cannot see.
  logic [26:0] r_expect_addr_c;
  assign r_expect_addr_c = (rstate_q == R_HWAIT) ? hist_addr(r_slot_q)
                                                 : dev_addr(r_slot_q, r_burst_q);

  // ==========================================================================
  // OUTPUTS
  // ==========================================================================
  assign r_ready_o = (rstate_q == R_IDLE);
  assign r_valid_o = (rstate_q == R_STREAM);
  assign r_sp_o    = r_ptr_q;
  assign r_fresh_o = r_fresh_q;
  assign h_ready_o = (rstate_q == R_STREAM);
  assign w_ready_o = (wstate_q == W_IDLE);
  assign busy_o    = (rstate_q != R_IDLE) || (wstate_q != W_IDLE) || w_slot_held_q;

  // The record currently offered, sliced out of the 512-bit burst.
  // `r_ptr_q[1:0]` is the record within the burst; `r_ptr_q[3:2]` selects
  // which burst is loaded, and the FSM keeps `r_burst_q` equal to it.
  // `r_rec_c[REC_BITS-1:RECW]` is the PADDING and has no reader by design --
  // see the header on why the record is 128 bits and not 88.  A lint waiver is
  // the honest statement of that; narrowing the slice would hide the padding
  // from anybody reading the decode.
  /* verilator lint_off UNUSEDSIGNAL */
  logic [REC_BITS-1:0] r_rec_c;
  /* verilator lint_on UNUSEDSIGNAL */
  logic [HISTW-1:0]    r_hist_c;
  always_comb begin
    r_rec_c  = r_row_q[({4'd0, r_ptr_q[1:0]} * REC_BITS) +: REC_BITS];
    r_hist_c = r_hist_q[({4'd0, r_ptr_q} * HISTW) +: HISTW];
  end

  assign r_dev1_o = r_fresh_q ? r_rec_c[0        +: DEVW] : DEV_MAX;
  assign r_dev2_o = r_fresh_q ? r_rec_c[DEVW     +: DEVW] : DEV_MAX;
  assign r_dev3_o = r_fresh_q ? r_rec_c[2 * DEVW +: DEVW] : DEV_MAX;
  // The centre height is answered even for a slot with no records: a wrong
  // distance to a patch drawn at full detail is a smaller fault than a wrong
  // level, and zero is the island datum rather than a poison value.
  assign r_cy_o   = r_fresh_q ? signed'(r_rec_c[3 * DEVW +: 16]) : 16'sd0;

  // `r_hist_q` is ZEROED when the slot has no committed history, so these
  // three read the neutral triple rather than a stranger's hysteresis.  See
  // the header: gating them here instead would put the same three constants
  // on a mux that a reader has to find.
  assign r_prev_level_o = r_hist_c[1:0];
  assign r_prev_morph_o = r_hist_c[2 +: MORPHW];
  assign r_hold_o       = r_hist_c[(2 + MORPHW) +: 8];

  // ==========================================================================
  // THE SEQUENTIAL CORE
  // ==========================================================================
  logic [REC_BITS-1:0] w_rec_c;
  assign w_rec_c = {{(REC_BITS - RECW) {1'b0}},
                    w_cy_i, w_dev3_i, w_dev2_i, w_dev1_i};

  logic [HISTW-1:0] h_rec_c;
  assign h_rec_c = {h_hold_i, h_morph_i, h_level_i};

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      mstate_q       <= M_IDLE;
      m_addr_q       <= 27'd0;
      m_write_q      <= 1'b0;
      m_owner_rd_q   <= 1'b0;
      m_rbuf_q       <= '0;
      m_wsh_q        <= '0;
      m_beat_q       <= 3'd0;
      m_done_q       <= 1'b0;
      m_fail_q       <= 1'b0;

      rstate_q       <= R_IDLE;
      r_slot_q       <= '0;
      r_burst_q      <= 2'd0;
      r_ptr_q        <= 4'd0;
      h_ptr_q        <= 4'd0;
      r_fresh_q      <= 1'b0;
      r_hfresh_q     <= 1'b0;
      h_any_q        <= 1'b0;
      r_row_q        <= '0;
      r_hist_q       <= '0;
      h_acc_q        <= '0;

      wstate_q       <= W_IDLE;
      w_acc_q        <= '0;
      w_out_q        <= '0;
      w_slot_q       <= '0;
      w_burst_q      <= 2'd0;
      w_last_q       <= 1'b0;
      w_slot_held_q  <= 1'b0;
      w_patch_done_o <= 1'b0;

      slot_valid_q   <= '0;
      hist_valid_q   <= '0;

      records_written_o   <= '0;
      patches_committed_o <= '0;
      patches_read_o      <= '0;
      read_unwritten_o    <= '0;
      hist_unwritten_o    <= '0;
      hist_step_bad_o     <= '0;
      invalidations_o     <= '0;
      guard_denied_o      <= '0;
      short_burst_o       <= '0;
      stray_beat_o        <= '0;
      slot_addr_bad_o     <= '0;
      bursts_read_o       <= '0;
      bursts_written_o    <= '0;
      rd_wait_clocks_o    <= '0;
    end else begin
      w_patch_done_o <= 1'b0;
      m_done_q       <= 1'b0;
      m_fail_q       <= 1'b0;

      // ---- invalidation.  A claim or a bake makes a slot's records stale,
      // and stale records are worse than none: they describe a lattice that
      // has been replaced.  R24's re-trigger arrives as a second mip pass;
      // until it commits, the slot reads DEV_MAX and is counted.  The HISTORY
      // is dropped with them -- see the header for why that is the safe
      // direction rather than a loss.
      if (inv_valid_i) begin
        slot_valid_q[inv_slot_i] <= 1'b0;
        hist_valid_q[inv_slot_i] <= 1'b0;
        invalidations_o <= invalidations_o + 32'd1;
      end

      // ---- a beat offered with no read in flight ---------------------------
      // The share BROADCASTS beat data and demuxes only `beat_valid`, so this
      // is the check that sees a wrong demux.  The address round trip cannot:
      // it compares two of this block's own registers and knows nothing about
      // whose bytes arrived.
      if (beat_valid_i && (mstate_q != M_RBEAT))
        stray_beat_o <= stray_beat_o + 32'd1;

      // ====================================================================
      // THE MEMORY ENGINE
      // ====================================================================
      case (mstate_q)
        M_IDLE: if (mo_start_c) begin
          m_owner_rd_q <= mo_rd_c;
          m_write_q    <= mo_rd_c ? rq_w_c : 1'b1;
          // ============ THE MUTATION, AND IT IS THIS ONE LINE ============
          // Production reloads the held address for EVERY op.  This copy
          // loads it once and then keeps it forever, which is the
          // register-an-address-unconditionally-and-then-not shape of the
          // metadata-swap defect CLAUDE.md records: the engine goes on
          // serving one address while the read FSM walks four bursts and a
          // history row.  `slot_addr_bad_o` is the only thing in the block
          // that can see it -- every handshake still balances, every burst is
          // still eight beats, and the guard still says the address is legal,
          // because it IS legal, just not this patch's.
          if (m_addr_q == 27'd0) m_addr_q <= mo_rd_c ? rq_a_c : wq_a_c;
          m_wsh_q      <= mo_rd_c ? rq_d_c : w_out_q;
          m_beat_q     <= 3'd0;
          m_rbuf_q     <= '0;
          mstate_q     <= M_REQ;
        end

        // The guard answers in TWO cycles: `ready` is a level, `ok` is pulsed
        // the cycle after the accept.  Testing them in one arm reads every
        // pass as a denial.
        M_REQ: if (guard_rsp_i.ready) mstate_q <= M_VERD;

        M_VERD: begin
          if (guard_rsp_i.violation) begin
            guard_denied_o <= guard_denied_o + 32'd1;
            m_fail_q       <= 1'b1;
            mstate_q       <= M_IDLE;
          end else if (guard_rsp_i.ok) begin
            m_beat_q <= 3'd0;
            mstate_q <= m_write_q ? M_WBEAT : M_RBEAT;
          end
        end

        M_RBEAT: if (beat_valid_i) begin
          // Little-endian word order: beat 0 ends in bits [63:0] after the
          // eighth shift, so byte 0 of the burst is bit 0 of the buffer.
          m_rbuf_q <= {beat_data_i, m_rbuf_q[BURST_W-1:64]};
          m_beat_q <= m_beat_q + 3'd1;
          if (beat_last_i) begin
            if (m_beat_q != 3'(BEATS - 1)) begin
              short_burst_o <= short_burst_o + 32'd1;
              m_fail_q      <= 1'b1;
            end else begin
              bursts_read_o <= bursts_read_o + 32'd1;
              m_done_q      <= 1'b1;
            end
            mstate_q <= M_IDLE;
          end
        end

        M_WBEAT: if (guard_wready_i) begin
          m_wsh_q  <= {64'd0, m_wsh_q[BURST_W-1:64]};
          m_beat_q <= m_beat_q + 3'd1;
          if (m_beat_q == 3'(BEATS - 1)) begin
            bursts_written_o <= bursts_written_o + 32'd1;
            m_done_q         <= 1'b1;
            mstate_q         <= M_IDLE;
          end
        end

        default: mstate_q <= M_IDLE;   // M_ACK is unused; a stray state exits
      endcase

      // ====================================================================
      // THE READ FSM
      // ====================================================================
      // Every memory-wait state is counted, so the SDRAM round trip is a
      // measured number rather than the paragraph above's claim.
      if ((rstate_q == R_HREQ) || (rstate_q == R_HWAIT)
          || (rstate_q == R_DREQ) || (rstate_q == R_DWAIT))
        rd_wait_clocks_o <= rd_wait_clocks_o + 32'd1;

      case (rstate_q)
        R_IDLE: if (r_start_i) begin
          r_slot_q   <= r_slot_i;
          r_fresh_q  <= slot_valid_q[r_slot_i];
          r_hfresh_q <= hist_valid_q[r_slot_i];
          r_ptr_q    <= 4'd0;
          h_ptr_q    <= 4'd0;
          r_burst_q  <= 2'd0;
          h_any_q    <= 1'b0;
          patches_read_o <= patches_read_o + 32'd1;
          if (!slot_valid_q[r_slot_i])
            read_unwritten_o <= read_unwritten_o + 32'd1;
          if (!hist_valid_q[r_slot_i])
            hist_unwritten_o <= hist_unwritten_o + 32'd1;
          rstate_q   <= R_HREQ;
        end

        R_HREQ: if (mo_start_c && mo_rd_c) rstate_q <= R_HWAIT;

        R_HWAIT: begin
          if (rd_ack_c) begin
            // A slot with no committed history answers the NEUTRAL triple, not
            // whatever SDRAM held -- see the header.
            r_hist_q <= r_hfresh_q ? m_rbuf_q[HROWW-1:0] : '0;
            h_acc_q  <= r_hfresh_q ? m_rbuf_q[HROWW-1:0] : '0;
            rstate_q <= R_DREQ;
          end else if (rd_fail_c) begin
            r_hist_q <= '0;
            h_acc_q  <= '0;
            rstate_q <= R_DREQ;
          end
        end

        R_DREQ: if (mo_start_c && mo_rd_c) rstate_q <= R_DWAIT;

        R_DWAIT: begin
          if (rd_ack_c) begin
            r_row_q  <= m_rbuf_q;
            rstate_q <= R_STREAM;
          end else if (rd_fail_c) begin
            // Degrade to "no records", never abandon the stream: the consumer
            // is waiting on `r_valid_o` and an abort would present as a hang.
            r_fresh_q <= 1'b0;
            r_row_q   <= '0;
            rstate_q  <= R_STREAM;
          end
        end

        R_STREAM: begin
          // The history record for the descriptor being retired.
          if (h_valid_i) begin
            if (h_ptr_q != r_ptr_q) hist_step_bad_o <= hist_step_bad_o + 32'd1;
            h_acc_q[({4'd0, h_ptr_q} * HISTW) +: HISTW] <= h_rec_c;
            h_ptr_q <= h_ptr_q + 4'd1;
            h_any_q <= 1'b1;
          end

          if (r_valid_o && r_ready_i) begin
            if (r_ptr_q == 4'd15) begin
              // The sixteenth record was already merged by the `h_valid_i`
              // block above, in this same cycle, so nothing is merged twice
              // here.  A patch whose LOD pass emitted NOTHING skips the write
              // entirely: the row would be byte-identical to the one just
              // read, and the bandwidth is the whole point of this move.
              // `h_any_q` has not taken this cycle's record yet, which is why
              // `h_valid_i` is in the test beside it.
              rstate_q <= (h_any_q || h_valid_i) ? R_HWR : R_IDLE;
            end else begin
              r_ptr_q <= r_ptr_q + 4'd1;
              if (r_ptr_q[1:0] == 2'd3) begin
                r_burst_q <= r_burst_q + 2'd1;
                rstate_q  <= R_DREQ;
              end
            end
          end
        end

        R_HWR: if (mo_start_c && mo_rd_c) rstate_q <= R_HWRW;

        R_HWRW: begin
          if (rd_ack_c) begin
            hist_valid_q[r_slot_q] <= 1'b1;
            rstate_q <= R_IDLE;
          end else if (rd_fail_c) begin
            // The row did not land, so the slot keeps whatever history it had
            // -- which is the conservative answer, and `guard_denied_o` says
            // why the next read is unfresh.
            rstate_q <= R_IDLE;
          end
        end

        default: rstate_q <= R_IDLE;
      endcase

      // THE ADDRESS ROUND TRIP, checked while a read op is in flight for this
      // patch.  Unreachable with legal stimulus; see the committed mutant.
      if (((rstate_q == R_HWAIT) || (rstate_q == R_DWAIT))
          && (mstate_q != M_IDLE) && m_owner_rd_q && !m_write_q
          && (m_addr_q != r_expect_addr_c))
        slot_addr_bad_o <= slot_addr_bad_o + 32'd1;

      // ====================================================================
      // THE WRITE FSM
      // ====================================================================
      case (wstate_q)
        W_IDLE: if (w_valid_i) begin
          records_written_o <= records_written_o + 32'd1;
          w_slot_held_q     <= 1'b1;
          // Place the record in the accumulator at its position within the
          // burst.  The fourth record never lands here -- it is merged on this
          // same cycle below.
          if (w_sp_i[1:0] != 2'd3)
            w_acc_q[({4'd0, w_sp_i[1:0]} * REC_BITS) +: REC_BITS] <= w_rec_c;
          else begin
            w_out_q   <= {w_rec_c, w_acc_q};
            w_slot_q  <= w_slot_i;
            w_burst_q <= w_sp_i[3:2];
            w_last_q  <= (w_sp_i[3:2] == 2'd3);
            wstate_q  <= W_REQ;
          end
        end

        W_REQ: if (mo_start_c && !mo_rd_c) wstate_q <= W_WAIT;

        W_WAIT: begin
          if (wr_ack_c) begin
            if (w_last_q) begin
              slot_valid_q[w_slot_q] <= 1'b1;
              patches_committed_o    <= patches_committed_o + 32'd1;
              w_patch_done_o         <= 1'b1;
              w_slot_held_q          <= 1'b0;
            end
            wstate_q <= W_IDLE;
          end else if (wr_fail_c) begin
            // A refused burst leaves the slot INVALID even if it was the last
            // one.  A patch whose records are three quarters written is worse
            // than a patch with none: the first answers plausible deviations
            // for four subpatches and stale ones for twelve, and nothing
            // downstream can tell.
            if (w_last_q) w_slot_held_q <= 1'b0;
            wstate_q <= W_IDLE;
          end
        end

        default: wstate_q <= W_IDLE;
      endcase
    end
  end

endmodule

`default_nettype wire
