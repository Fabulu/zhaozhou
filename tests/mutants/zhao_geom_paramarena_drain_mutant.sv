// ---------------------------------------------------------------------------
// THE AUTHORIZED MAP, AND WHAT THIS BLOCK IS ALLOWED TO DO IN IT
// ---------------------------------------------------------------------------
//   [0x0600_0000, 0x0640_0000)  view 0, 4 MiB
